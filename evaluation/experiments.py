"""Experiment suite. Every number written to results/ comes from an actual run.

All methods are evaluated on the SAME held-out map seeds (paired comparison).
Training maps use seeds < evaluation.heldout_seed_offset; evaluation maps use
seeds >= that offset, so every evaluation map is unseen during training.
"""
import copy
import csv
import os
import shutil
import time

from backends.simulation_backend import SimulationBackend
from evaluation.evaluate import (dqn_method, with_recovery, evaluate_method, heldout_seeds, load_dqn, load_qlearning,
                                 planner_methods, qlearning_method, run_episode)
from visualization.plots import (plot_comparison_bars, plot_sweep, plot_training_run, plot_trajectories)

SUMMARY_KEYS = ["success_rate", "success_ci_low", "success_ci_high", "collision_rate", "timeout_rate",
                "no_path_rate", "mean_path_ratio_success", "mean_steps_success", "mean_path_length_success",
                "mean_inference_ms", "mean_planning_ms", "mean_nodes_expanded", "interventions_per_episode"]


def _write_csv(rows, path):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def _row(method, setting, stats):
    return {"method": method, **setting, **{k: round(stats[k], 4) for k in SUMMARY_KEYS}}


def _md_table(rows, cols, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        cells = []
        for c in cols:
            v = r[c]
            cells.append(f"{v:.2f}" if isinstance(v, float) else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


class ExperimentRunner:
    def __init__(self, cfg, dqn_path, q_path, out_dir):
        self.cfg = cfg
        self.out = out_dir
        os.makedirs(out_dir, exist_ok=True)
        self.dqn_agent, self.train_cfg = load_dqn(dqn_path)
        self.methods = {"DQN": dqn_method(self.dqn_agent)}
        self.methods["DQN + recovery"] = with_recovery(dqn_method(self.dqn_agent), self.train_cfg)
        if q_path and os.path.exists(q_path):
            self.methods["Q-learning"] = qlearning_method(load_qlearning(q_path)[0])
        for m in planner_methods(cfg):
            self.methods[m.name] = m
        self.n = cfg.evaluation.episodes_per_setting
        self.seeds = heldout_seeds(cfg, self.n)
        self.md = ["# Experiment results", "",
                   f"Generated by `python main.py experiments` on {time.strftime('%Y-%m-%d %H:%M')}.",
                   f"{self.n} held-out maps per setting (seeds {self.seeds[0]}-{self.seeds[-1]}), identical "
                   "for every method. \"+ recovery\" = navigation-layer stuck recovery around the same DQN; "
                   "\"+ shield\" = safety layer active (the full deployment configuration).", ""]

    def _eval(self, name, cfg=None, **kw):
        use_safety = name.endswith("+ shield")
        method = self.methods[name.replace(" + shield", "")]
        return evaluate_method(cfg or self.cfg, method, self.seeds, use_safety=use_safety, **kw)

    def _sweep(self, key, label, values, methods, kwarg, fname, title, metrics=("success_rate", "collision_rate")):
        rows = []
        for v in values:
            for m in methods:
                t0 = time.perf_counter()
                stats, _ = self._eval(m, **{kwarg: v})
                rows.append(_row(m, {key: v}, stats))
                print(f"  {key}={v:<5} {m:<24} success {stats['success_rate']:.2f}  "
                      f"collision {stats['collision_rate']:.2f}  ({time.perf_counter() - t0:.0f}s)", flush=True)
        _write_csv(rows, os.path.join(self.out, f"{fname}.csv"))
        plot_sweep(rows, key, label, title, os.path.join(self.out, f"{fname}.png"), metrics)
        return rows

    # ---------------- experiments ----------------
    def training(self, run_dirs):
        self.md += ["## 1. Training progress", ""]
        for name, run in run_dirs.items():
            if run and os.path.isdir(run):
                plot_training_run(run, name)
                dst = os.path.join(self.out, f"training_{name.lower().replace('-', '')}.png")
                shutil.copy(os.path.join(run, "training_curves.png"), dst)
                self.md.append(f"![{name} training]({os.path.basename(dst)})")
        self.md.append("")

    def comparison(self):
        print("[comparison] default density", flush=True)
        names = [m for m in ["DQN", "DQN + recovery", "DQN + recovery + shield", "Q-learning", "A*", "Dijkstra"]
                 if m.replace(" + shield", "") in self.methods]
        stats = {}
        for m in names:
            stats[m], _ = self._eval(m)
        rows = [_row(m, {"density": self.cfg.world.obstacle_density}, s) for m, s in stats.items()]
        _write_csv(rows, os.path.join(self.out, "comparison.csv"))
        plot_comparison_bars(stats, os.path.join(self.out, "comparison.png"),
                             f"Held-out maps, obstacle density {self.cfg.world.obstacle_density}")
        self.md += [f"## 2. Method comparison (density {self.cfg.world.obstacle_density}, {self.n} unseen maps)", "",
                    "A* / Dijkstra are given the full static map and the true pose; DQN and Q-learning only see "
                    "24 range readings plus goal distance/bearing. Path ratio = driven length / shortest "
                    "path to the goal circle (successful episodes only).", "",
                    _md_table(rows, ["method", "success_rate", "success_ci_low", "success_ci_high", "collision_rate",
                                     "timeout_rate", "mean_path_ratio_success", "mean_steps_success",
                                     "mean_inference_ms", "mean_planning_ms", "mean_nodes_expanded"],
                              ["Method", "Success", "CI low", "CI high", "Collision", "Timeout", "Path ratio",
                               "Steps", "Decision ms/step", "Planning ms", "Nodes expanded"]),
                    "", "![comparison](comparison.png)", ""]
        self._example_trajectories()

    def _example_trajectories(self, n_maps=3):
        for i, seed in enumerate(self.seeds[:n_maps]):
            trajs, plans, world = {}, {}, None
            for name in ("DQN", "DQN + recovery", "A*"):
                if name not in self.methods:
                    continue
                backend, collected = SimulationBackend(self.cfg), []
                ep = run_episode(self.cfg, self.methods[name], seed, backend=backend,
                                 on_step=lambda r, c=collected: c.append((r.pose.x, r.pose.y)))
                world = backend.world
                trajs[f"{name} ({ep.outcome})"] = [world.start[:2]] + collected
                print(f"  example map {seed}: {name} -> {ep.outcome}", flush=True)
            plot_trajectories(world, trajs, os.path.join(self.out, f"trajectories_{i}.png"),
                              f"Held-out map {seed}", cfg=self.cfg)
        self.md += ["Example trajectories on held-out maps:", "",
                    " ".join(f"![traj](trajectories_{i}.png)" for i in range(n_maps)), ""]

    def density(self):
        print("[density sweep]", flush=True)
        methods = [m for m in ["DQN", "DQN + recovery", "DQN + recovery + shield", "Q-learning", "A*", "Dijkstra"]
                   if m.replace(" + shield", "") in self.methods]
        rows = self._sweep("density", "obstacle density (fraction of area)", self.cfg.evaluation.densities,
                           methods, "density", "density_sweep", "Effect of obstacle density",
                           ("success_rate", "collision_rate", "mean_path_ratio_success"))
        self.md += ["## 3. Effect of obstacle density", "",
                    "Training used densities sampled from "
                    f"{list(self.train_cfg.randomization.obstacle_density)}.", "",
                    _md_table(rows, ["density", "method", "success_rate", "collision_rate", "timeout_rate",
                                     "mean_path_ratio_success"],
                              ["Density", "Method", "Success", "Collision", "Timeout", "Path ratio"]),
                    "", "![density](density_sweep.png)", ""]

    def generalization(self):
        print("[generalization]", flush=True)
        variants = {
            "in-distribution (unseen maps)": {},
            "denser than training (0.30)": {"density": 0.30},
            "small clutter (0.15-0.35 m)": {"world.obstacle_size": [0.15, 0.35]},
            "long walls (1.0-2.5 m)": {"world.obstacle_size": [1.0, 2.5]},
            "3 moving obstacles": {"num_movers": 3},
        }
        rows = []
        for vname, change in variants.items():
            cfg = copy.deepcopy(self.cfg)
            kw = {}
            for k, v in change.items():
                if k.startswith("world."):
                    cfg.world[k.split(".")[1]] = v
                else:
                    kw[k] = v
            for m in [x for x in ["DQN", "DQN + recovery", "DQN + recovery + shield", "Q-learning", "A*"] if x.replace(" + shield", "") in self.methods]:
                stats, _ = self._eval(m, cfg=cfg, **kw)
                rows.append(_row(m, {"condition": vname}, stats))
                print(f"  {vname:<32} {m:<24} success {stats['success_rate']:.2f} collision "
                      f"{stats['collision_rate']:.2f}", flush=True)
        _write_csv(rows, os.path.join(self.out, "generalization.csv"))
        self.md += ["## 4. Generalisation to unseen and out-of-distribution maps", "",
                    "No evaluation map was used in training. The out-of-distribution conditions change map "
                    "statistics beyond anything in training (moving obstacles were never present in training). "
                    "A* plans on the static map only, so it cannot anticipate moving obstacles.", "",
                    _md_table(rows, ["condition", "method", "success_rate", "collision_rate", "timeout_rate",
                                     "mean_path_ratio_success"],
                              ["Condition", "Method", "Success", "Collision", "Timeout", "Path ratio"]), ""]

    def noise(self):
        print("[sensor noise sweep]", flush=True)
        ev = self.cfg.evaluation
        methods = [m for m in ["DQN", "DQN + recovery", "DQN + recovery + shield", "Q-learning", "A*"] if m.replace(" + shield", "") in self.methods]
        s_rows = self._sweep("sensor_noise", "range noise std (m)", ev.sensor_noise_levels, methods,
                             "sensor_noise", "sensor_noise_sweep", "Effect of range-sensor noise")
        print("[motion noise sweep]", flush=True)
        m_rows = self._sweep("motion_noise", "relative velocity noise std", ev.motion_noise_levels, methods,
                             "motion_noise", "motion_noise_sweep", "Effect of motion (actuation) noise")
        self.md += ["## 5. Sensor noise and motion uncertainty", "",
                    "Training randomised sensor noise in "
                    f"{list(self.train_cfg.randomization.sensor_noise_std)} m and motion noise "
                    f"{self.train_cfg.randomization.motion_noise_std}. A* uses the true map and true pose, so range "
                    "noise does not affect it; motion noise affects its path follower.", "",
                    "### Range sensor noise", "",
                    _md_table(s_rows, ["sensor_noise", "method", "success_rate", "collision_rate", "timeout_rate"],
                              ["Noise std (m)", "Method", "Success", "Collision", "Timeout"]),
                    "", "![sensor noise](sensor_noise_sweep.png)", "", "### Motion noise", "",
                    _md_table(m_rows, ["motion_noise", "method", "success_rate", "collision_rate", "timeout_rate"],
                              ["Noise std", "Method", "Success", "Collision", "Timeout"]),
                    "", "![motion noise](motion_noise_sweep.png)", ""]

    def dynamic(self):
        print("[moving obstacles]", flush=True)
        methods = [m for m in ["DQN", "DQN + recovery", "DQN + recovery + shield", "A*"] if m.replace(" + shield", "") in self.methods]
        rows = self._sweep("moving_obstacles", "number of moving obstacles", [0, 2, 4], methods,
                           "num_movers", "dynamic_obstacles", "Moving obstacles (never seen in training)")
        self.md += ["## 6. Moving obstacles", "",
                    _md_table(rows, ["moving_obstacles", "method", "success_rate", "collision_rate", "timeout_rate"],
                              ["Moving obstacles", "Method", "Success", "Collision", "Timeout"]),
                    "", "![dynamic](dynamic_obstacles.png)", ""]

    def write_summary(self):
        with open(os.path.join(self.out, "RESULTS.md"), "w", encoding="utf-8") as f:
            f.write("\n".join(self.md) + "\n")


def run_all(cfg, dqn_path, q_path, out_dir, only=None, run_dirs=None):
    t0 = time.perf_counter()
    r = ExperimentRunner(cfg, dqn_path, q_path, out_dir)
    only = set(only or ["training", "comparison", "density", "generalization", "noise", "dynamic"])
    if "training" in only:
        r.training(run_dirs or {})
    for name in ("comparison", "density", "generalization", "noise", "dynamic"):
        if name in only:
            getattr(r, name)()
            r.write_summary()
    r.write_summary()
    print(f"Done in {time.perf_counter() - t0:.0f}s. Results in {os.path.abspath(out_dir)}/RESULTS.md")
