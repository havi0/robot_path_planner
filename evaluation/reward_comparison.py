"""Controlled comparison used for the collision fix: old vs. new reward, 3 training seeds each,
evaluated (greedy, NO safety shield) on the 45 shared-benchmark scenarios x 2 repeats.

    python -m evaluation.reward_comparison
"""
import json
import math
import os
import sys
import time

import numpy as np
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import load_config  # noqa: E402
from evaluation.evaluate import load_dqn  # noqa: E402
from evaluation.metrics import wilson_interval  # noqa: E402
from evaluation.recorder import record_episode  # noqa: E402
from server.stores import JsonCollection  # noqa: E402

MODELS = {
    "old reward": ["models/dqn.pt", "runs/fix/old_s1/best.pt", "runs/fix/old_s2/best.pt"],
    "new reward": ["runs/fix/new_s0/best.pt", "runs/fix/new_s1/best.pt", "runs/fix/new_s2/best.pt"],
}


def main(repeats=2):
    cfg = load_config()
    scen = JsonCollection("data/scenarios", "sc")
    sset = JsonCollection("data/scenario_sets", "set").get("benchmark-v1")
    scenarios = [scen.get(i) for i in sset["scenario_ids"]]
    out = {}
    for group, paths in MODELS.items():
        per_seed = []
        for path in paths:
            agent, acfg = load_dqn(path)
            res = {"success": 0, "collision": 0, "timeout": 0, "n": 0, "causes": {}}
            for sc in scenarios:
                for r in range(repeats):
                    ep = record_episode(cfg, sc["world"], "dqn", {"sensor_noise": 0.02, "motion_noise": 0.05, "shield": False},
                                        10_000 * (1 + r) + (sc["seed"] % 10_000), agent, acfg, source="comparison")
                    res[ep["outcome"]] += 1
                    res["n"] += 1
                    if ep["outcome"] == "collision":
                        c = ep["metrics"]["collision"]["cause"]
                        res["causes"][c] = res["causes"].get(c, 0) + 1
            per_seed.append({"model": path, **res})
            print(f"{group:10s} {path:28s} success {res['success']/res['n']:.2f} collision {res['collision']/res['n']:.2f} "
                  f"timeout {res['timeout']/res['n']:.2f}", flush=True)
        out[group] = per_seed
    summary = {}
    for g, rows in out.items():
        n = sum(r["n"] for r in rows)
        summary[g] = {k: {"pooled": sum(r[k] for r in rows) / n, "ci": wilson_interval(sum(r[k] for r in rows), n),
                          "per_seed": [r[k] / r["n"] for r in rows]} for k in ("success", "collision", "timeout")}
        summary[g]["n"] = n
    tests = {}
    for k in ("success", "collision", "timeout"):
        a, b = summary["old reward"][k]["per_seed"], summary["new reward"][k]["per_seed"]
        tests[k] = float(stats.ttest_ind(a, b, equal_var=False).pvalue)
    json.dump({"per_seed": out, "summary": summary, "welch_p": tests, "time": time.time()},
              open("results/collision_fix_comparison.json", "w"), indent=2)
    lines = ["# Reward fix: controlled comparison", "",
             "Greedy DQN, **no safety shield**, shared benchmark (45 unseen scenarios x 2 repeats = 90 episodes per model), "
             "3 training seeds per reward. Generated by `python -m evaluation.reward_comparison`.", "",
             "| Reward | Success (pooled, 95% CI) | Collision (pooled, 95% CI) | Timeout (pooled) | per-seed collision |", "|---|---|---|---|---|"]
    for g, s in summary.items():
        lines.append(f"| {g} | {s['success']['pooled']:.1%} [{s['success']['ci'][0]:.1%}-{s['success']['ci'][1]:.1%}] | "
                     f"{s['collision']['pooled']:.1%} [{s['collision']['ci'][0]:.1%}-{s['collision']['ci'][1]:.1%}] | "
                     f"{s['timeout']['pooled']:.1%} | {', '.join(f'{x:.1%}' for x in s['collision']['per_seed'])} |")
    lines += ["", "Welch t-test across seeds (n=3 vs 3): " + ", ".join(f"{k} p={p:.3f}" for k, p in tests.items())]
    open("results/collision_fix_comparison.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
