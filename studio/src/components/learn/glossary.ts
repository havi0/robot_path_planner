const norm = (s: string) =>
  s.toLowerCase().replace(/\s+/g, " ").trim().replace(/\s*\(n\s*=\s*\d+\)$/, "").replace(/:$/, "").trim();

const INDEX = new Map<string, LearnEntry>();
for (const e of GLOSSARY) for (const a of e.aliases) INDEX.set(norm(a), e);
const BY_ID = new Map(GLOSSARY.map((e) => [e.id, e]));

export function lookupText(text: string): LearnEntry | undefined {
  if (!text || text.length > 64) return undefined;
  return INDEX.get(norm(text));
}

export function lookupId(id: string): LearnEntry | undefined {
  return BY_ID.get(id);
}

export function pageGuide(pathname: string) {
  if (pathname === "/") return PAGE_GUIDES["/"];
  const key = Object.keys(PAGE_GUIDES).filter((k) => k !== "/" && pathname.startsWith(k)).sort((a, b) => b.length - a.length)[0];
  return key ? PAGE_GUIDES[key] : undefined;
}
